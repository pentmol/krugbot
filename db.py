    async def pick_next_video(self, viewer_user_id: int) -> Optional[Video]:
        async with self.pool.connection() as conn:
            cur = conn.cursor()

            # First show videos the user has never seen.
            await cur.execute(
                """
                WITH candidates AS (
                    SELECT v.id, v.owner_user_id, v.file_id,
                           u.age, u.gender, u.looking_for, u.about
                    FROM videos v
                    JOIN users u ON u.user_id = v.owner_user_id
                    WHERE v.owner_user_id != %s
                      AND u.video_hidden = FALSE
                      AND NOT EXISTS (
                        SELECT 1
                        FROM views vw
                        WHERE vw.viewer_user_id = %s
                          AND vw.video_id = v.id
                      )
                )
                SELECT id, owner_user_id, file_id, age, gender, looking_for, about
                FROM candidates
                ORDER BY
                    CASE WHEN owner_user_id IN (
                        SELECT active_chat_user_id
                        FROM users
                        WHERE active_chat_user_id IS NOT NULL
                    ) THEN 0 ELSE 1 END,
                    (
                        SELECT u2.last_chat_activity_at
                        FROM users u2
                        WHERE u2.user_id = candidates.owner_user_id
                    ) DESC NULLS LAST,
                    (
                        SELECT v2.created_at
                        FROM videos v2
                        WHERE v2.id = candidates.id
                    ) DESC
                LIMIT 1;
                """,
                (viewer_user_id, viewer_user_id),
            )
            row = await cur.fetchone()
            if row:
                return Video(
                    id=row["id"],
                    owner_user_id=row["owner_user_id"],
                    file_id=row["file_id"],
                    age=row["age"],
                    gender=row["gender"],
                    looking_for=row["looking_for"],
                    about=row["about"],
                )

            # If everyone has already been seen, start showing them again.
            # Do not repeat anyone from the last 5 viewed profiles when possible.
            await cur.execute(
                """
                SELECT v.id, v.owner_user_id, v.file_id,
                       u.age, u.gender, u.looking_for, u.about
                FROM videos v
                JOIN users u ON u.user_id = v.owner_user_id
                WHERE v.owner_user_id != %s
                  AND u.video_hidden = FALSE
                  AND NOT EXISTS (
                    SELECT 1
                    FROM (
                      SELECT v2.owner_user_id
                      FROM views vw2
                      JOIN videos v2 ON v2.id = vw2.video_id
                      WHERE vw2.viewer_user_id = %s
                      ORDER BY vw2.viewed_at DESC
                      LIMIT 5
                    ) recent
                    WHERE recent.owner_user_id = v.owner_user_id
                  )
                ORDER BY
                    CASE WHEN u.active_chat_user_id IS NOT NULL THEN 0 ELSE 1 END,
                    u.last_chat_activity_at DESC NULLS LAST,
                    v.created_at DESC
                LIMIT 1;
                """,
                (viewer_user_id, viewer_user_id, viewer_user_id),
            )
            row = await cur.fetchone()

            # With fewer than 6 available profiles, a strict 5-profile cooldown
            # can leave no candidate. In that case, use the oldest viewed profile.
            if not row:
                await cur.execute(
                    """
                    SELECT v.id, v.owner_user_id, v.file_id,
                           u.age, u.gender, u.looking_for, u.about
                    FROM videos v
                    JOIN users u ON u.user_id = v.owner_user_id
                    JOIN views vw ON vw.video_id = v.id AND vw.viewer_user_id = %s
                    WHERE v.owner_user_id != %s
                      AND u.video_hidden = FALSE
                    ORDER BY
                        CASE WHEN u.active_chat_user_id IS NOT NULL THEN 0 ELSE 1 END,
                        u.last_chat_activity_at DESC NULLS LAST,
                        vw.viewed_at ASC
                    LIMIT 1;
                    """,
                    (viewer_user_id, viewer_user_id),
                )
                row = await cur.fetchone()

            if not row:
                return None
            return Video(
                id=row["id"],
                owner_user_id=row["owner_user_id"],
                file_id=row["file_id"],
                age=row["age"],
                gender=row["gender"],
                looking_for=row["looking_for"],
                about=row["about"],
            )

