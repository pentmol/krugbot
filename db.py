    async def delete_video_by_id(self, video_id: int) -> Optional[int]:
        async with self.pool.connection() as conn:
            cur = conn.cursor()
            await cur.execute("SELECT owner_user_id FROM videos WHERE id=%s;", (video_id,))
            row = await cur.fetchone()
            if not row:
                return None
            owner_user_id = int(row["owner_user_id"])
